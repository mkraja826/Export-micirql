test('synthetic benchmark cases have unique IDs, both classes, and traceable labels',()=>{
 const ids=cases.map(entry=>entry.id);
 assert.equal(new Set(ids).size,ids.length);
 assert.ok(cases.filter(entry=>entry.truth).length>=8);
 assert.ok(cases.filter(entry=>!entry.truth).length>=15);
 for(const c of cases)assert.ok(c.report&&Array.isArray(c.report.issueCenter));
});

test('critical-risk benchmark must have zero false alarms or missed critical cases',()=>{
 let tp=0,fp=0,tn=0,fn=0;
 const errors=[];
 for(const c of cases){
  const prior=JSON.stringify(c.report);
  const result=assessSeoSiteRisk(c.report);
  const prediction=result.level==='critical';
  if(c.truth&&prediction)tp++;
  else if(!c.truth&&prediction)fp++;
  else if(!c.truth&&!prediction)tn++;
  else fn++;
  if(result.level!==c.level)errors.push(c.id+': expected '+c.level+', got '+result.level);
  if(result.numericScore!==null)errors.push(c.id+': numeric score must remain disabled');
  if(JSON.stringify(c.report)!==prior)errors.push(c.id+': mutated source report');
 }
 const precision=tp+fp?tp/(tp+fp):0;
 const recall=tp+fn?tp/(tp+fn):0;
 const falsePositiveRate=fp+tn?fp/(fp+tn):0;
 console.log('SYNTHETIC risk gate only (not real-world accuracy): '+
  JSON.stringify({cases:cases.length,tp,fp,tn,fn,precision,recall,falsePositiveRate}));
 assert.deepEqual(errors,[],'Scenario labels must match, without mutating input');
 assert.equal(fp,0,'No synthetic critical-risk false positives allowed');
 assert.equal(fn,0,'No synthetic critical-risk false negatives allowed');
});
