// Chromium A4 regression: full 60-page printable Unified Website Health PDF.
// Synthetic evidence only: validates layout and disclaimers, not external sites.
import {chromium} from 'playwright';
import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {execFileSync} from 'node:child_process';
import {resolve} from 'node:path';
const html=(await readFile(resolve('public/tools/health/index.html'),'utf8'))
 .replace(/<script type="module" src="\/tools\/health\/app\.js"><\/script>/,'');
const dir=resolve('dist/unified-health-pdf-fixtures');await mkdir(dir,{recursive:true});
const browser=await chromium.launch({headless:true});
try{
 const page=await browser.newPage({viewport:{width:1100,height:850}});
 const errors=[];page.on('pageerror',err=>errors.push(err.message));
 await page.setContent(html,{waitUntil:'load'});
 await page.evaluate(()=>{
  document.getElementById('results').hidden=false;
  document.getElementById('website').textContent='https://health-fixture.example/';
  document.getElementById('date').textContent='Generated by MiCirql synthetic PDF verification';
  const metrics=document.getElementById('metrics');
  for(const [label,value] of [['Source pages checked','58 / 60'],
   ['Confirmed broken links','3'],['Responsive review signals','2'],
   ['Security review candidates','5']]){
   const node=document.createElement('div');node.className='metric';
   const valueNode=document.createElement('strong');valueNode.textContent=value;
   const labelNode=document.createElement('span');labelNode.textContent=label;
   node.append(valueNode,labelNode);metrics.append(node);
  }
  document.getElementById('coverage').textContent='58 complete, 2 unverified page snapshots. One HTML capture reused across SEO, QA, Accessibility and Links. No single overall website score.';
  const addFinding=(parent,title,description)=>{
   const row=document.createElement('div');row.className='finding';
   const strong=document.createElement('strong');strong.textContent=title;
   const p=document.createElement('p');p.textContent=description;row.append(strong,p);
   parent.append(row);
  };
  addFinding(document.getElementById('priorities'),'HIGH · Links · Confirmed broken internal link',
   'https://health-fixture.example/broken · HTTP 404; linked from home page');
  addFinding(document.getElementById('priorities'),'REVIEW · SEO · Missing title',
   'https://health-fixture.example/about; heuristic HTML evidence');
  for(const [label,state,detail] of [
   ['SEO inspection','partial','58/60 source snapshots. Per-page HTML scores are not search ranking predictions.'],
   ['QA Testing Lab','partial','Static HTML checks only, no journey execution.'],
   ['Link & Sitemap Inspector','partial','3 observed HTTP 404/410, 4 destinations unverified.'],
   ['Responsive Lab','partial','375px, 768px, 1440px; overflow observations require review.'],
   ['Accessibility Studio','partial','Source review candidates; manual WCAG conformance validation required.'],
   ['Security Inspector','checked','Passive headers only; missing headers are not confirmed vulnerabilities.'],
   ['Performance Lab','checked','One unthrottled Chrome navigation; FCP not observed.'],
   ['Screenshot Studio','not_run','No screenshots were captured; separate opt-in ZIP capture.']
  ]){
   const container=document.createElement('section');container.className='sect';
   const header=document.createElement('div');header.className='sect-title';
   const h=document.createElement('h2');h.textContent=label;
   const badge=document.createElement('span');badge.className='mark';badge.textContent=state;
   header.append(h,badge);container.append(header);
   const p=document.createElement('p');p.className='small muted';p.textContent=detail;container.append(p);
   addFinding(container,label+' coverage','Unverified checks are not successful findings.');
   document.getElementById('sections').append(container);
  }
  const tbody=document.getElementById('pages');
  for(let i=0;i<60;i++){
   const tr=document.createElement('tr');
   const fields=['https://health-fixture.example/page-'+i,
    i<58?'complete':'unverified',i<58?'—':'navigation unavailable'];
   for(const field of fields){const td=document.createElement('td');td.textContent=field;tr.append(td)}
   tbody.append(tr);
  }
  for(const line of ['No single health score has been assigned.',
   'Blocked and unverified HTTP destinations are not confirmed broken links.',
   'Browser overflow is not proof of clipping or visual overlap.',
   'LCP, CLS and INP are not verified field Core Web Vitals.',
   'No target website modifications or automatic repairs were made.']){
   const li=document.createElement('li');li.textContent=line;
   document.getElementById('limitations').append(li);
  }
 });
 if(await page.locator('#pages tr').count()!==60)throw Error('Missing 60-page evidence rows before printing');
 const path=resolve(dir,'unified-60-pages.pdf');
 await writeFile(path,await page.pdf({format:'A4',printBackground:true,preferCSSPageSize:true}));
 const all=execFileSync('pdftotext',['-layout',path,'-'],{encoding:'utf8',maxBuffer:6000000})
  .replace(/\s+/g,' ');
 for(const phrase of ['MiCirql Website Health Report','Recommended priorities',
  'SEO inspection','QA Testing Lab','Link & Sitemap Inspector','Responsive Lab',
  'Accessibility Studio','Security Inspector','Performance Lab','Screenshot Studio',
  'https://health-fixture.example/page-59','LCP, CLS and INP are not verified']){
  if(!all.includes(phrase))throw Error('Unified PDF is missing '+phrase);
 }
 const count=Number(execFileSync('pdfinfo',[path],{encoding:'utf8'}).match(/^Pages:\s*(\d+)/m)?.[1]||0);
 if(count<2||count>24)throw Error('Unexpected A4 page count: '+count);
 const last=execFileSync('pdftotext',['-f',String(count),'-l',String(count),path,'-'],{encoding:'utf8'});
 if(last.trim().length<35)throw Error('Final unified PDF page is blank');
 if(errors.length)throw Error('Unified PDF browser error(s): '+errors.join('; '));
 console.log('Unified Website Health 60-page A4 PDF: '+count+' pages; evidence and final-page checks passed');
}finally{await browser.close()}
