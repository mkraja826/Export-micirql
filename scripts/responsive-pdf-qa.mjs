// Chromium A4 print regression for Responsive Lab's three-width evidence report.
// Static synthetic layout evidence, never a claim about a real customer's website.
import {chromium} from 'playwright';
import {readFile,mkdir,writeFile} from 'node:fs/promises';
import {execFileSync} from 'node:child_process';
import {resolve} from 'node:path';
const markup=(await readFile(resolve('public/tools/responsive/index.html'),'utf8'))
 .replace(/<script type="module" src="\/tools\/responsive\/app\.js"><\/script>/,'');
const dir=resolve('dist/responsive-pdf-fixtures');
await mkdir(dir,{recursive:true});
const browser=await chromium.launch({headless:true});
try{
 const page=await browser.newPage({viewport:{width:1120,height:800}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.setContent(markup,{waitUntil:'load'});
 await page.evaluate(()=>{
  document.getElementById('results').hidden=false;
  document.getElementById('website').textContent='https://fixture.example';
  document.getElementById('report-date').textContent='Generated by synthetic layout QA';
  const metrics=document.getElementById('metrics');
  for(const [title,value] of [['Verified viewport checks','8 / 9'],
   ['Horizontal overflow signals',2],['Mobile scaling or viewport signals',1],
   ['Unverified viewport checks',1]]){
   const box=document.createElement('div');box.className='metric';
   const big=document.createElement('strong');big.textContent=value;
   const label=document.createElement('span');label.textContent=title;
   box.append(big,label);metrics.append(box);
  }
  document.getElementById('coverage').textContent='Sampled 3 of 60 discovered public pages. This is not a whole-site responsive pass.';
  for(const text of ['375px · https://fixture.example/ · CSS document exceeds observed viewport by 46px',
   '768px · https://fixture.example/about · CSS document exceeds observed viewport by 9px']){
   const p=document.createElement('p');p.className='note';p.textContent=text;
   document.getElementById('signals').append(p);
  }
  for(const url of ['https://fixture.example/','https://fixture.example/contact','https://fixture.example/about']){
   const section=document.createElement('section');section.className='page';
   const title=document.createElement('h3');title.textContent=url;section.append(title);
   const columns=document.createElement('div');columns.className='measurements';
   for(const width of [375,768,1440]){
    const card=document.createElement('div');card.className='measure';
    const h=document.createElement('strong');h.textContent=width+'px · Measured';
    const detail=document.createElement('p');
    detail.textContent='CSS viewport '+width+'px; document width '+(width+(width===375?46:0))+'px; horizontal overflow '+(width===375?46:0)+'px.';
    card.append(h,detail);columns.append(card);
   }
   section.append(columns);document.getElementById('pages').append(section);
  }
  for(const text of ['Three sampled pages cannot represent complete-site responsive correctness',
   'A zero-overflow observation does not prove visual usability or absence of clipping']){
   const li=document.createElement('li');li.textContent=text;document.getElementById('limitations').append(li);
  }
 });
 const output=resolve(dir,'responsive-three-page-evidence.pdf');
 await writeFile(output,await page.pdf({format:'A4',printBackground:true,preferCSSPageSize:true}));
 const text=execFileSync('pdftotext',['-layout',output,'-'],{encoding:'utf8'}).replace(/\s+/g,' ');
 for(const phrase of ['Responsive Layout Report','Horizontal overflow signals','Viewport observations',
  'https://fixture.example/contact','1440px','Three sampled pages cannot represent complete-site'])
  if(!text.includes(phrase))throw Error('Responsive PDF omitted '+phrase);
 const count=Number(execFileSync('pdfinfo',[output],{encoding:'utf8'}).match(/^Pages:\s*(\d+)/m)?.[1]);
 if(!Number.isInteger(count)||count<1||count>10)throw Error('Invalid responsive PDF pagination: '+count);
 const tail=execFileSync('pdftotext',['-f',String(count),'-l',String(count),output,'-'],{encoding:'utf8'});
 if(tail.trim().length<30)throw Error('Responsive PDF final page is empty');
 if(errors.length)throw Error('Responsive report browser error: '+errors.join('; '));
 console.log('Responsive Lab A4 PDF: '+count+' pages, responsive evidence and limits preserved');
}finally{await browser.close()}
