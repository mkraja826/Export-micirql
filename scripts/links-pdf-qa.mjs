// Chromium print regression for the standalone Link & Sitemap Inspector.
// Synthetic data only; verifies printable evidence, pagination and nonblank last page.
import {chromium} from 'playwright';
import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {execFileSync} from 'node:child_process';
import {resolve} from 'node:path';
const html=(await readFile(resolve('public/tools/links/index.html'),'utf8'))
 .replace(/<script type="module" src="\/tools\/links\/app\.js"><\/script>/,'');
await mkdir(resolve('dist/links-pdf-fixtures'),{recursive:true});
const browser=await chromium.launch({headless:true});
try{
 const page=await browser.newPage({viewport:{width:1100,height:850}});
 const errors=[];page.on('pageerror',error=>errors.push(error.message));
 await page.setContent(html,{waitUntil:'load'});
 await page.evaluate(()=>{
  document.getElementById('results').hidden=false;
  document.getElementById('website').textContent='https://fixture.example';
  document.getElementById('report-date').textContent='Generated by synthetic QA';
  const metrics=document.getElementById('metrics');
  for(const [label,value] of [['Confirmed broken (404/410)',3],['HTTP server errors (5xx)',2],
   ['Reachable destinations',50],['Unverified or unchecked',5]]){
   const div=document.createElement('div');div.className='metric';
   const b=document.createElement('strong');b.textContent=value;
   const small=document.createElement('small');small.textContent=label;
   div.append(b,small);metrics.append(div);
  }
  document.getElementById('scope').textContent='58 of 60 selected pages inspected successfully. 60 of 65 unique internal link destinations checked. Unverified outcomes are not counted as broken.';
  document.getElementById('sitemap').textContent='Sitemap verification: observed HTTP 200; 60 listed URLs. This is not full XML schema validation.';
  document.getElementById('pages').textContent='58 complete, 2 unverified. End of report coverage statement.';
  const table=document.getElementById('destinations');
  for(let i=0;i<60;i++){
   const tr=document.createElement('tr');
   for(const value of ['https://f.test/p/'+i,i<3?'Confirmed broken':i<5?'Server error':i<10?'Unverified':'Reachable',i<3?'404':i<5?'503':'200','https://f.test/s/'+i]){
    const cell=document.createElement('td');cell.textContent=value;tr.append(cell);
   }
   table.append(tr);
  }
 });
 const pdf=await page.pdf({format:'A4',printBackground:true,preferCSSPageSize:true});
 const output=resolve('dist/links-pdf-fixtures/links-60-page-evidence.pdf');
 await writeFile(output,pdf);
 const text=execFileSync('pdftotext',['-layout',output,'-'],{encoding:'utf8',maxBuffer:5_000_000}).replace(/\s+/g,' ');
 for(const phrase of ['Link & Sitemap Report','Confirmed broken','Sitemap verification',
  'https://f.test/p/59','https://f.test/s/59','End of report coverage statement'])
  if(!text.includes(phrase))throw Error('Link inspector PDF missing '+phrase);
 const count=Number(execFileSync('pdfinfo',[output],{encoding:'utf8'}).match(/^Pages:\s*(\d+)/m)?.[1]||0);
 if(count<2||count>25)throw Error('Link inspector report pagination outside reasonable bounds: '+count);
 const last=execFileSync('pdftotext',['-f',String(count),'-l',String(count),output,'-'],{encoding:'utf8'});
 if(last.trim().length<35)throw Error('Link inspector PDF final page is blank');
 if(errors.length)throw Error('Link inspector PDF page errors: '+errors.join('; '));
 console.log('Link & Sitemap Inspector 60-link A4 PDF: '+count+' pages, evidence and final-page checks passed');
 await page.close();
}finally{await browser.close()}
